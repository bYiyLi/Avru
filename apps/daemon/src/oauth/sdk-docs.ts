/** Index entries only (no full content), in table order. */
export function sdkDocIndex(): {
  topic: string;
  title: string;
  description: string;
}[] {
  return SDK_DOCS.map(({ topic, title, description }) => ({
    topic,
    title,
    description,
  }));
}
/** Documents for the requested topics, in request order. Throws TOPIC_NOT_FOUND naming the topic. */
export function sdkDocs(topics: string[]): SdkDoc[] {
  return topics.map((topic) => {
    const doc = SDK_DOCS.find((item) => item.topic === topic);
    if (!doc) throw new Error(`TOPIC_NOT_FOUND: ${topic}`);
    return doc;
  });
}
